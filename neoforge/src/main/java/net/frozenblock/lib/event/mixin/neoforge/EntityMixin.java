import com.llamalad7.mixinextras.injector.wrapoperation.Operation;
import com.llamalad7.mixinextras.injector.wrapoperation.WrapOperation;
import net.frozenblock.lib.event.api.events.ServerEntityLevelChangeEvents;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.level.portal.TeleportTransition;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;

@Mixin(Entity.class)
public class EntityMixin {

	@WrapOperation(
		method = "teleport",
		at = @At(
			value = "INVOKE",
			target = "Lnet/minecraft/world/entity/Entity;teleportCrossDimension(Lnet/minecraft/server/level/ServerLevel;Lnet/minecraft/server/level/ServerLevel;Lnet/minecraft/world/level/portal/TeleportTransition;)Lnet/minecraft/world/entity/Entity;"
		)
	)
	private Entity frozenLib$fabric$afterDimensionChanged(Entity instance, ServerLevel oldLevel, ServerLevel newLevel, TeleportTransition transition, Operation<Entity> original) {
		// This will only have an entity if the teleport worked (entity not removed, teleportTarget was valid, entity was successfully created)
		final Entity newEntity = original.call(instance, oldLevel, newLevel, transition);

		if (newEntity != null) {
			ServerEntityLevelChangeEvents.AFTER_ENTITY_CHANGE_LEVEL.invoker().afterChangeLevel(
				Entity.class.cast(this), newEntity, oldLevel, newLevel
			);
		}

		return newEntity;
	}
}
