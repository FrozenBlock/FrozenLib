package net.frozenblock.lib.advancement.api.predicates.entity;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import net.minecraft.advancements.predicates.entity.EntitySubPredicate;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.Mob;
import net.minecraft.world.phys.Vec3;
import org.jspecify.annotations.Nullable;

public final class MobPredicate implements EntitySubPredicate {
	public static final MobPredicate INSTANCE = new MobPredicate();
	public static final Codec<MobPredicate> CODEC = RecordCodecBuilder.create(instance -> instance.point(INSTANCE));

	@Override
	public boolean matches(Entity entity, ServerLevel serverLevel, @Nullable Vec3 vec3) {
		return entity instanceof Mob;
	}
}
